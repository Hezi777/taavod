import { mkdir, copyFile, readdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../..');
const packageRoot = path.dirname(require.resolve('@electric-sql/pglite'));
const destination = path.join(root, 'public/practice/runtime');
await mkdir(destination, {recursive:true});
const files=(await readdir(packageRoot)).filter(name=>name.endsWith('.js')||['pglite.wasm','initdb.wasm','pglite.data'].includes(name));
for(const name of files) await copyFile(path.join(packageRoot,name),path.join(destination,name));
console.log('Practice runtime assets ready.');
